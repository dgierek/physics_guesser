# Third party imports:
import torch
import matplotlib.pyplot as plt
import numpy as np
from sklearn.decomposition import PCA

# Self written library imports:
import datasets
import autoencoder

# Load the trained model
model = autoencoder.AutoencoderWithEvolution(latent_dim=10)
model.load_state_dict(torch.load("saved_models\\trained_on_400_simul_lr_params_0.001_25_0.9_recon_loss_only_latent_dim_10.pth"))
model.eval()  # Set to evaluation mode

# Select a sample image from the dataset
dataset = datasets.LoadedDataset(preloaded_dataset_file_name='preloaded_test_data.pt')
sample_idx = 0  # Change index to visualize different images
sample_image = dataset[sample_idx][1].unsqueeze(0)  # Selecting the middle image in the triplet
sample_image = sample_image.to("cuda" if torch.cuda.is_available() else "cpu")

# Run the image through the model
with torch.no_grad():
    reconstructed, _, _ = model(sample_image)

# Convert tensors to numpy for plotting
original_img = sample_image.squeeze(0).permute(1, 2, 0).cpu().numpy()
reconstructed_img = reconstructed.squeeze(0).permute(1, 2, 0).cpu().numpy()

# Plot the original vs reconstructed image
fig, ax = plt.subplots(1, 2, figsize=(10, 5))

ax[0].imshow(original_img)
ax[0].set_title("Original Image")
ax[0].axis("off")

ax[1].imshow(reconstructed_img)
ax[1].set_title("Reconstructed Image")
ax[1].axis("off")

plt.tight_layout()
plt.show()

# Reconstruction of the trajectory:
# Loading the original trajectory
x_original = np.load(r'simulation_frames/gravity_0/gravity_x_coords.npy')
y_original = np.load(r'simulation_frames/gravity_0/gravity_y_coords.npy')

# Getting the latent space vectors:
z = []

for data in dataset:
    x_curr= data[1].unsqueeze(0)

    with torch.no_grad():
        latent_vector = model.encoder(x_curr)

    z.append(latent_vector.cpu().detach().numpy())

z = np.concatenate(z, axis=0)

# Performing PCA to reduce the dimensionality:
pca = PCA(n_components=2)
z_reduced = pca.fit_transform(z)

# Visualizing the original trajectory and trajectory generated by the net:
fig, (ax1, ax2) = plt.subplots(1, 2)

ax1.plot(x_original, y_original, linewidth=0.5)

ax1.set_xlim(0, 10)
ax1.set_ylim(0, 10)
ax1.set_aspect('equal')
ax1.set_title('Original trajectory')

ax2.plot(z_reduced[:,0], z_reduced[:,1], linewidth=0.5)
ax2.set_title('Reconstructed trajectory')

plt.tight_layout()
plt.show(block=True)

plt.plot(x_original, y_original, linewidth=1.5, label='Original trajectory')
plt.plot(z_reduced[:,0], z_reduced[:,1], linewidth=1.5, label='Reconstructed trajectory')
plt.legend()
plt.ylim(-1 + np.min(z_reduced[:,1]), 10)
plt.xlim(-1 + np.min(z_reduced[:,0]), 10)
plt.title('Trajectory reconstruction')
plt.show(block=True)
