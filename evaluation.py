from autoencoder import AutoencoderWithEvolution
from torch import load, device, cuda
from datasets import ImageDataset, collate_fn
from torch.utils.data import DataLoader
from torchvision import transforms
import numpy as np
from sklearn.decomposition import PCA
import matplotlib.pyplot as plt

# Loading in saved model
device = device('cuda' if cuda.is_available() else 'cpu')
print('Device:', str(device))

model = AutoencoderWithEvolution().to(device)
model.load_state_dict(load(r'saved_models/trained_on_10_simulations.pth'))
model.eval()

# Loading test data:
transform = transforms.Compose([
    transforms.Resize((64, 64)),  # down sampling the resolution of the images
    transforms.ToTensor()
])
dataset = ImageDataset(directory=r'simulation_frames/gravity_test_0/simulation_snapshots', transform=transform)
dataloader = DataLoader(dataset, batch_size=1, shuffle=False, collate_fn=collate_fn)

# Loading the original trajectory
x_original = np.load(r'simulation_frames/gravity_test_0/gravity_test_x_coords.npy')
y_original = np.load(r'simulation_frames/gravity_test_0/gravity_test_y_coords.npy')

# Getting the latent space vectors:
z = []

for _, data in dataloader:
    _, x_curr, _ = data.squeeze(0).to(device)
    x_curr = x_curr.unsqueeze(0)
    latent_vector = model.encoder(x_curr)
    z.append(latent_vector.cpu().detach().numpy())

z = np.concatenate(z, axis=0)
#print(z.shape)

# Performing PCA to reduce the dimensionality:
pca = PCA(n_components=2)
z_reduced = pca.fit_transform(z)
#print(z_reduced.shape)
print(z_reduced)

# Visualizing the original trajectory and trajectory generated by the net:
fig, (ax1, ax2) = plt.subplots(1, 2)

ax1.plot(x_original, y_original, linewidth=0.5)

ax1.set_xlim(0, 10)
ax1.set_ylim(0, 10)
ax1.set_aspect('equal')

ax2.plot(z_reduced[:,0], z_reduced[:,1], linewidth=0.5)

ax2.set_xlim(-5, 5)
ax2.set_ylim(-5, 5)
ax2.set_aspect('equal')

plt.tight_layout()
plt.show()